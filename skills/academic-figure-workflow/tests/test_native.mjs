import assert from 'node:assert/strict';
import {gridCells,viewport,createFigure} from '../scripts/figure-native.mjs';
const cells=gridCells({x:10,y:20,width:100,height:60,rows:2,cols:2,gapX:4,gapY:6});
assert.deepEqual(cells,[{x:10,y:20,width:48,height:27},{x:62,y:20,width:48,height:27},{x:10,y:53,width:48,height:27},{x:62,y:53,width:48,height:27}]);
assert.throws(()=>gridCells({x:0,y:0,width:1,height:1,rows:0,cols:2}));
assert.throws(()=>gridCells({x:0,y:0,width:1,height:1,rows:1,cols:2,gapX:5}));
const v=viewport([0,0,10,5],{x:10,y:20,width:100,height:100});
assert.deepEqual(v.point([0,0]),[10,45]);assert.deepEqual(v.point([10,5]),[110,95]);
assert.equal(v.x(3)-v.x(1),v.y(3)-v.y(1));
assert.throws(()=>viewport([0,0,0,1],{x:0,y:0,width:10,height:10}));
assert.throws(()=>createFigure({widthMm:182,heightMm:90,style:{}},{}));
const captured=[];
const fake={Presentation:{create:()=>({slides:{add:()=>({background:{},shapes:{add:config=>{captured.push(config);const text={};return Object.defineProperty({...config},'text',{get:()=>text,set:value=>{text.value=value;}});}},speakerNotes:{textFrame:{setText:()=>{}}}})}})},PresentationFile:{}};
const f=createFigure({widthMm:100,heightMm:50,style:{font:'Arial',fontPt:9.5,arrowMm:.3,headMm:1.2}},fake);
const c=f.addCanvas();
c.arrow('straight',[[10,10],[30,10]]);c.bezier('curved',[[10,20],[15,35],[25,35],[30,20]]);
assert.equal(captured.find(x=>x.name==='straight').line.width,captured.find(x=>x.name==='curved').line.width);
assert.equal(captured.filter(x=>x.name.endsWith('-head')).length,2);
assert.throws(()=>c.arrow('tiny',[[0,0],[.1,0]]));
assert.throws(()=>c.bezier('bad-tangent',[[0,0],[1,1],[2,2],[2,2]]));
assert.throws(()=>c.arrow('straight',[[1,1],[10,1]]));
console.log('Geometry tests passed: relative grid anchors, aspect-preserving viewport, invalid geometry guards.');
